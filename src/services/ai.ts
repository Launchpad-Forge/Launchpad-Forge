/**
 * AI Provider Abstraction
 * 
 * Allows swapping between OpenAI, Anthropic, Gemini, Groq, or Local LLMs
 * without altering the UI logic (e.g., for generating proposals or summarizing leads).
 */

export interface AIAdapter {
  generateText(prompt: string, context?: string): Promise<string>;
  summarize(text: string): Promise<string>;
}

class MockAIAdapter implements AIAdapter {
  async generateText(prompt: string, context?: string): Promise<string> {
    console.log(`[MockAI] Generating text for prompt: ${prompt}`);
    return "This is a mock AI response generated by the system.";
  }

  async summarize(text: string): Promise<string> {
    console.log(`[MockAI] Summarizing text of length: ${text.length}`);
    return "This is a mock summary.";
  }
}

// Future implementation would connect to Langchain or direct SDKs
export function getAIProvider(): AIAdapter {
  const provider = process.env.AI_PROVIDER || 'mock';
  
  // Switch logic here based on ENV
  return new MockAIAdapter();
}

export const ai = getAIProvider();
